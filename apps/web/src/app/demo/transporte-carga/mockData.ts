const createFacturaItem = (
  descripcion: string,
  cantidad: number,
  valorUnitario: number,
  afectacionIgv: '10' | '20' = '20'
): FacturaItem => {
  const precioUnitario = valorUnitario;
  const subtotal = cantidad * precioUnitario;
  const igvRate = afectacionIgv === '10' ? 0.1 : 0.18;
  const igv = subtotal * igvRate;
  const total = subtotal + igv;

  return {
    id: `item-${Math.random().toString(36).substr(2, 9)}`,
    descripcion,
    unidad: 'ZZ',
    cantidad,
    valorUnitario,
    precioUnitario,
    igv,
    total,
    afectacionIgv,
  };
};

